def _count(jobs, outs, ns):
    "Runs that flagged each sentence, and runs that gave a verdict on it, for documents of `ns` sentences"
    votes,judged = ([[0]*n for n in ns] for _ in range(2))
    for (k,c,_),vs in zip(jobs, outs):
        if isinstance(vs, Exception): continue
        for i,_ in c:
            if i not in vs: continue
            judged[k][i] += 1
            votes[k][i] += vs[i]
    return votes,judged

