def _chunks(sents, max_words=1000):
    "Runs of whole paragraphs of about `max_words` words, as lists of (number, `Sent`) pairs"
    res,cur,n = [],[],0
    for _,g in itertools.groupby(enumerate(sents), lambda o: o[1].para):
        g = list(g)
        w = sum(len(s.text.split()) for _,s in g)
        if cur and n+w > max_words: res,cur,n = res+[cur],[],0
        cur,n = cur+g,n+w
    return res+[cur] if cur else res

