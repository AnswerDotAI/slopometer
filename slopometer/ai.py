_verdict = re.compile(r'^\W*(\d+)\W+(?:\1\W+)?([HF])\b', re.M)
def parse_verdicts(txt):
    "Sentence number -> True for `H`, from a reply with one verdict per line"
    return {int(i): v == 'H' for i,v in _verdict.findall(txt)}

