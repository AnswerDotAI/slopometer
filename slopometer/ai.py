def ai_prompt(chunk, seed=None):
    "Prompt asking for `H` or `F` on each sentence of `chunk`, a list of (number, `Sent`) pairs; `seed` shuffles the examples"
    a,b = groups()
    if seed is not None:
        for g in (a,b): random.Random(seed).shuffle(g)
    lines,prev = [],None
    for i,s in chunk:
        if prev not in (None, s.para): lines.append('')
        lines.append(f'[{i}] {s.text}')
        prev = s.para
    nl = '\n'
    return f"""Some sentences make the reader stop and work out what really happened and who did it.

Hard sentences:

{nl.join(a)}

Fine sentences:

{nl.join(b)}

Judge each numbered sentence below in the same way. Answer with one line per sentence, in the form `12 H` for a hard sentence or `12 F` for a fine one, and nothing else.

{nl.join(lines)}"""

