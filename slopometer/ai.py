class Sent:
    def __init__(self,
        start, # Character offset of the sentence in the document
        end, # Character offset one past its end
        text, # The sentence on one line, with inline code kept and other markup removed
        para, # Index of its paragraph or list item among the judged blocks
    ): store_attr()
    def __repr__(self): return f'<{self.para} @{self.start}: {self.text!r}>'

_tags = re.compile(r'^[ \t]*(?:</?[A-Za-z][\w:.-]*>[ \t]*)+$', re.M)
_stop = re.compile(r'''[.?!]['")\]*_]*$''')
def _quoted(s, i):
    "Is position `i` of `s` inside a double-quoted passage that closes later?"
    return (s.count('"', 0, i)%2 == 1 and '"' in s[i:]) or (s.count('“', 0, i) > s.count('”', 0, i) and '”' in s[i:])

_seen = re.compile(r"""<https?://[^\s>]+>|(?<!\]\()https?://[^\s<>\[\]]*[^\s<>\[\]().,;:!?'"]|(?<![\w`])__[a-z][a-z0-9_]*?__(?![\w`])""")
def _keep(o, s):
    "`s`, the scrubbed `o`, with the URLs and dunder names that a reader of `o` sees copied back from it"
    for m in _seen.finditer(o): s = s[:m.start()] + m[0] + s[m.end():]
    return s
_abbr = re.compile(r'(?<![\w.])(?:incl|excl|approx|cf|esp|resp|viz|ca|fig|figs|eq|eqs|sec|vol|al|misc|est|avg|std|ref|refs|ex|e\.g|i\.e|etc|vs|no|nos|pp)\.$', re.I)

def sentences(txt, min_words=3):
    "Sentences of `min_words`+ words in the paragraphs and list items of markdown `txt`; a newline ends a sentence"
    blocks = [b for b in segment(txt) if b.kind != 'heading']
    def clean(b):
        s = _tags.sub(lambda m: ' '*len(m[0]), _keep(b.txt, scrub(b.txt)))
        m = _item.match(s) if b.kind == 'item' else None
        return ' '*m.end() + s[m.end():] if m else s
    lines = [(k, b, m.start(), m[0]) for k,b in enumerate(blocks) for m in re.finditer(r'[^\n]+', clean(b))]
    res = []
    for (k,b,off,_),d in zip(lines, get_nlp().pipe(l[3] for l in lines)):
        spans = []
        for s in d.sents:
            toks = [t for t in s if not t.is_space]
            if not toks: continue
            a,e = toks[0].idx, toks[-1].idx+len(toks[-1])
            prev = d.text[spans[-1][0]:spans[-1][1]] if spans else ''
            if spans and (spans[-1][1] == a or _quoted(d.text, a) or not _stop.search(prev) or (_abbr.search(prev) and not d.text[a].isupper())): spans[-1][1] = e
            else: spans.append([a, e])
        for a,e in spans:
            ws = ''.join(o for o,c in zip(b.txt[off+a:off+e], d.text[a:e]) if c != ' ' or o.isspace()).split()
            if len(ws) >= min_words: res.append(Sent(b.start+off+a, b.start+off+e, ' '.join(ws), k))
    return res

