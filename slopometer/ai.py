class AIFinding(Finding):
    def __init__(self,
        start, # Character offset where the sentence starts
        end, # Character offset one past its end
        text, # The sentence
        votes, # Runs that flagged it
        judged, # Runs that gave a verdict on it
    ):
        super().__init__('ai', None, start, end, text, votes)
        store_attr('votes,judged')
    def __repr__(self): return f'[{self.votes}/{self.judged}] {self.text!r}'

class AIResult(Result):
    def __init__(self,
        txt, # The judged document
        words, # Word count across all scored blocks
        sents=(), # Every `Sent` sent to the model
        votes=(), # Runs that flagged each of `sents`
        judged=(), # Runs that gave a verdict on each of `sents`
        runs=5, # Runs made
    ):
        fs = [AIFinding(s.start, s.end, s.text, v, j) for s,v,j in zip(sents, votes, judged) if v]
        super().__init__(txt, sorted(fs, key=lambda f: (-f.votes, f.start)), words, min_words=0)
        store_attr('sents,votes,judged,runs')
    @property
    def missing(self):
        "Verdicts that failed calls and incomplete replies left out"
        return sum(self.runs-j for j in self.judged)
    def _header(self):
        res = f'{len(self.findings)} of {len(self.sents)} sentences flagged in any of {self.runs} runs ({self.density}%), worst {self.worst}'
        return f'{res}, {self.missing} verdicts missing' if self.missing else res
    def as_dict(self):
        "JSON-ready record of every sentence sent to the model, with its votes and source location"
        return dict(path=self.path and str(self.path), words=self.words, runs=self.runs, missing=self.missing,
            sentences=[dict(n=i, text=s.text, para=s.para, votes=v, judged=j, **self.location(s))
                for i,(s,v,j) in enumerate(zip(self.sents, self.votes, self.judged))])

@patch(as_prop=True)
def density(self:AIResult):
    "Percentage of the sentences that any run flagged"
    return round(100*len(self.findings)/max(len(self.sents), 1), 1)

