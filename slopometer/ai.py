async def _ask(job, model):
    "Verdicts on a chunk for one run, from `job`, a (chunk, run number) pair; the exception if the call fails"
    chunk,run = job
    from fastllm.acomplete import acomplete
    from fastllm.chat import contents
    from aidialog.msg_parts import mk_msgs
    try: c = await acomplete(mk_msgs([ai_prompt(chunk, run)]), model, system=SYSTEM, reasoning_effort='low')
    except Exception as e: return e
    return parse_verdicts(contents(c).text)

async def ai_texts(
    txts, # Markdown documents
    runs=5, # Times to send each chunk
    model=MODEL, # `fastllm` model path
    n_workers=16, # Model calls in flight at once, across all documents
):
    "One `AIResult` per document in `txts`, flagging each sentence that any run calls hard"
    docs = [(t, scored_words(segment(t)), sentences(t)) for t in txts]
    jobs = [(k, c, r) for k,(_,_,ss) in enumerate(docs) for c in _chunks(ss) for r in range(runs)]
    outs = await parallel_async(_ask, [(c, r) for _,c,r in jobs], model, n_workers=n_workers)
    votes,judged = _count(jobs, outs, [len(ss) for _,_,ss in docs])
    if jobs and not any(map(any, judged)): raise first(outs, risinstance(Exception)) or RuntimeError(f'{model} gave no verdicts')
    return [AIResult(t, w, ss, v, j, runs) for (t,w,ss),v,j in zip(docs, votes, judged)]

@delegates(ai_texts)
async def ai_paths(paths, **kwargs):
    "One `AIResult` per file in `paths`, which takes what `score_paths` takes, with exhash addresses"
    read = [_read_file(p) for p in _doc_paths(paths)]
    rs = await ai_texts([t for t,_ in read], **kwargs)
    for r,(_,loc) in zip(rs, read): vars(r).update(loc)
    return rs
