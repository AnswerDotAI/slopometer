def _dedent(t):
    "`t` without the indentation that its later lines share, and a function that maps an offset in the result to its offset in `t`"
    lines = t.splitlines(keepends=True)
    ws = [len(l)-len(l.lstrip(' \t')) for l in lines]
    ind = min((w for l,w in zip(lines[1:], ws[1:]) if l.strip()), default=0)
    cuts = [0] + [min(ind, w) for w in ws[1:]]
    dst,ost = (list(itertools.accumulate(ns, initial=0)) for ns in ([len(l)-c for l,c in zip(lines, cuts)], map(len, lines)))
    def back(p):
        i = min(bisect_right(dst, p), len(lines)) - 1
        return ost[i] + cuts[i] + p - dst[i]
    return ''.join(l[c:] for l,c in zip(lines, cuts)), back

