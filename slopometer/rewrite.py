def _prose(path):
    "Each sentence, heading and other part of the prose in the file at `path` as (text, address, note); the note says when the text is a docstring or in an exported Markdown cell"
    path,res = Path(path),[]
    cells = {c.id: c for c in read_nb(path).cells} if path.suffix == '.ipynb' else {}
    for nm,ps in file_docs(path)[1]:
        if nm == CODE: continue
        for s,t in ps:
            addr = getattr(s, 'addr', None)
            c = cells.get(addr.split(':')[0]) if addr else None
            note = 'module docstring' if nm is None else f'docstring of `{nm}`' if nm else 'exported Markdown cell' if c and 'export' in c.directives else ''
            res.append((s.text if s else t, addr, note))
    return res

def _hunks(a, b):
    "Old texts `a` and new texts `b` of one changed stretch as (olds, news) pairs: a new pair starts at each old text that still has a similar new text"
    def sim(o, j): return SequenceMatcher(None, o, b[j]).ratio()
    cuts,k = [],0
    for i,o in enumerate(a):
        j = max(range(k, len(b)), key=partial(sim, o), default=None)
        if j is not None and sim(o, j) > 0.4: cuts,k = cuts+[(i, j)],j+1
    cuts = [(0, 0)] + cuts[1:] + [(len(a), len(b))]
    return [(a[i:x], b[j:y]) for (i,j),(x,y) in itertools.pairwise(cuts)]

def review_diff(
    path, # File that was reviewed and then edited
    out=None, # Folder that `rewrite_review` wrote to; `review_dir(path)` if None
    n=None, # Show only what changed during review `n`, counting from 1; every change since the first review if None
):
    "What differs between the original that the first review saved and the file at `path` now, or with `n` what changed during one review: the file's name, then each changed sentence or heading under its address, as `-` lines and the `+` lines that replace them"
    path,out,orig,d = _review(path, out, n)
    a,b = orig,path
    if n is not None:
        ds = _passes(path, out)
        a,b = _seen(d, path),next((_seen(o, path) for o in ds[ds.index(d)+1:]), path)
    a,b = _prose(a),_prose(b)
    res = []
    for tag,i,j,k,l in SequenceMatcher(None, [o[0] for o in a], [o[0] for o in b], autojunk=False).get_opcodes():
        if tag == 'equal': continue
        for olds,news in _hunks([o[0] for o in a[i:j]], [o[0] for o in b[k:l]]):
            _,addr,note = b[k] if news else a[i]
            hd = ' '.join(([f'@{addr}'] if addr else []) + ([f'({note})'] if note else []))
            res.append('\n'.join(([hd] if hd else []) + [f'- {o}' for o in olds] + [f'+ {o}' for o in news or ['(removed)']*bool(olds)]))
            i,k = i+len(olds),k+len(news)
    return '\n\n'.join([f"# {path}: {len(res)} change{'s'*(len(res) != 1)}{f' during review {d.name}' if n is not None else ''}"] + res)

