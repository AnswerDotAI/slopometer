ASKS = dict(carbon=('gemini/models/gemini-4-carbon', 'low'), sol=('gpt-6.1-sol', 'medium'))

def _save_orig(path, orig, last, fresh=False):
    "Save the file at `path` as `orig` when there is none, or when `fresh`, which first moves the present one into `last`, the folder of the latest review"
    if orig.exists() and not fresh: return
    if orig.exists() and last: orig.replace(last/orig.name)
    orig.write_bytes(path.read_bytes())

async def rewrite_review(
    path, # File to review, or a list of them: Markdown, a notebook, or a `.py` file for its docstrings
    out=None, # Folder to write to; `review_dir(path)` if None
    template=None, # Prompt with a `{document}` placeholder; `prompt()` if None
    asks=ASKS, # Name of each answer and its (model, effort)
    fills=None, # Text that each `{name}` placeholder in the sentences stands for
    context=None, # Files that the models can consult, such as the code that a document describes
    code=False, # Show each notebook code cell under the first run that explains it?
    brief=False, # Return only the runs that a model asked about or that every model changed?
    fresh=False, # Save the file as a new original? The original that it replaces moves into the folder of the latest review
    skip=None, # Regex; a paragraph or list item that it matches gets `[-]` in place of each number
    earlier=None, # File that holds an earlier version, for `? lost:` answers; the original that the first review saved if None and the file has changed since
    mod_only=False, # Give `[-]` to the docstrings of functions and classes? For a pyskill, whose module docstring is the skill's text
):
    "Ask each model in `asks` about the file at `path`; write the original to `out`, and a copy of the file, the input, each reply and their `compare` text to a new numbered folder in `out`; return that text, or one text for each file of a list; `brief` shortens what is returned, not what is written"
    if is_listy(path): return await asyncio.gather(*[rewrite_review(p, out, template, asks, fills, context, code, brief, fresh, skip, earlier, mod_only) for p in path])
    path,out,orig,last = _review(path, out)
    _,docs,_ = file_docs(path)
    if earlier is None and orig.exists() and not fresh and orig.read_bytes() != path.read_bytes(): earlier = orig
    replies = await asyncio.gather(*[ask_reply(docs, template, m, e, None, fills, context, skip, earlier, mod_only) for m,e in asks.values()])
    (d := out/str(int(last.name)+1 if last else 1)).mkdir(parents=True, exist_ok=True)
    for nm,r in zip(asks, replies): (d/f'{path.stem}.{nm}.answer.txt').write_text(r)
    _save_orig(path, orig, last, fresh)
    _seen(d, path).write_bytes(path.read_bytes())
    (d/f'{path.stem}.input.txt').write_text(rewrite_input(docs, fills, skip, mod_only=mod_only))
    ans = {nm: parse_rewrites(r) for nm,r in zip(asks, replies)}
    (d/f'{path.stem}.compare.txt').write_text(res := compare(docs, ans, code=code))
    return compare(docs, ans, code=code, brief=True) if brief else res

