def review_passed(
    path, # File that has been reviewed
    out=None, # Folder that `rewrite_review` wrote to; `review_dir(path)` if None
    n=None, # Review to read, counting from 1; the latest if None
):
    "The numbered sentences that no model rewrote or asked about in one review of the file at `path`: a count, then each as its number, address and text, with a line that names each docstring"
    path,out,_,d = _review(path, out, n)
    if not d: raise ValueError(f'{path} has no review in {out}')
    docs = file_docs(_seen(d, path))[1]
    _numbers_ok(path, d, sum(1 for _,ps in docs for s,_ in ps if s))
    skip = {k for k,m in enumerate(_marks(d, path) or []) if m == '-'}
    hit = {i for c in _answers(d, path).values() for a,b,_ in _changes(docs, c) for i in range(a, b+1)} | skip
    res,i,tot = [],0,0
    for nm,ps in docs:
        rows = []
        for s in (s for s,_ in ps if s):
            if i not in hit: rows.append(f"{i} {f'@{s.addr} ' if getattr(s, 'addr', None) else ''}{s.text}")
            i += 1
        if rows: res.append('\n'.join(([] if nm == '' else ['Module docstring:' if nm is None else f'Docstring of `{nm}`:']) + rows))
        tot += len(rows)
    return '\n\n'.join([f'{tot} of {i-len(skip)} sentences that no model changed in review {d.name}.'] + res)
