def _sents(path): return [s.text for _,ps in file_docs(path)[1] for s,_ in ps if s]

def review_apply(
    path, # File to edit
    edits, # New text for each sentence or run, or an empty one to delete it; a key is a number or (first, last) pair from the comparison, or the old text itself
    out=None, # Folder that `rewrite_review` wrote to; `review_dir(path)` if None
    n=None, # Review whose numbers the keys use, counting from 1; the latest if None
):
    "Put each new text of `edits` into the file at `path` in place of the sentences that its key names; if any edit cannot be made, raise `ValueError` that lists them all, and write nothing"
    path,out,_,d = _review(path, out, n)
    src,docs,valid = file_docs(path)
    cur = [s.text for _,ps in docs for s,_ in ps if s]
    old = _sents(_seen(d, path)) if d else cur
    if d and not all(isinstance(k, str) for k in edits): _numbers_ok(path, d, len(old))
    at = {x: y for tag,i,j,k,l in SequenceMatcher(None, old, cur, autojunk=False).get_opcodes() if tag == 'equal' for x,y in zip(range(i, j), range(k, l))}
    ans,bad = [],[]
    for key,t in edits.items():
        if isinstance(key, str):
            want = ' '.join(key.split())
            hits = [(i, j) for i in range(len(cur)) for j in range(i, min(i+8, len(cur))) if ' '.join(cur[i:j+1]) == want]
            if len(hits) == 1: ans.append((*hits[0], t))
            else: bad.append(f'{key!r}: found {len(hits)} times')
        else:
            a,b = (key, key) if isinstance(key, int) else key
            if all(n in at for n in range(a, b+1)) and at[b]-at[a] == b-a: ans.append((at[a], at[b], t))
            else: bad.append(f'{_rng(a, b)}: not in the review, or edited since')
    rw = Rewrites(src, docs, ans, valid=valid)
    bad += [f'{o!r}: crosses a paragraph, overlaps another edit, or changes the code' for *_,kind,o,_ in rw.rows if kind == 'LEFT OUT']
    if bad: raise ValueError('No edit was written.\n' + '\n'.join(bad))
    write_new(path, rw.new)
    return f"{len(rw.of('AFTER'))} of {len(edits)} edits changed {path}"

