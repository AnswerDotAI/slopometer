def _answers(d, path):
    "Each model's name with its answers, from the replies that the review in folder `d` saved for the file at `path`"
    pat = re.compile(re.escape(path.stem) + r'\.([^.]+)\.answer\.txt')
    return {m[1]: parse_rewrites(f.read_text()) for f in sorted(d.iterdir()) if (m := pat.fullmatch(f.name))}

def _marks(d, path):
    "The mark before each sentence in the input that the models read in the review in folder `d`: its number, or `-` for a sentence they were not asked about; None when that review saved no input"
    f = d/f'{path.stem}.input.txt'
    return re.findall(r'(?m)^(?:> |[-*+] |\d+[.)] )?\[(\d+|-)\] ', f.read_text()) if f.exists() else None

def _numbers_ok(path, d, n):
    "Raise `ValueError` unless the input that the models read in the review in folder `d` showed `n` sentences, as this version of the package does"
    seen = n if (ms := _marks(d, path)) is None else len(ms)
    if seen != n: raise ValueError(f'Review {d.name} of {path} numbered {seen} sentences and this version finds {n}: run `rewrite_review` on it again, or key the edits by their old text')

