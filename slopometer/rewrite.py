def review_dir(path):
    "The folder under XDG state that holds the review files for the file at `path`"
    return xdg_state_home()/'slopometer'/'rewrites'/str(Path(path).expanduser().resolve().with_suffix('')).lstrip('/')

def _seen(d, path): return d/f'{path.stem}.reviewed{path.suffix}'

def _passes(path, out):
    "The numbered folders in `out` that each hold one review of the file at `path`, oldest first. Review files that an older version left in `out` itself are first moved into a new numbered folder."
    if not out.exists(): return []
    orig = out/f'{path.stem}.orig{path.suffix}'
    ds = sorted((d for d in out.iterdir() if d.name.isdigit() and _seen(d, path).exists()), key=lambda d: int(d.name))
    if old := [f for f in out.glob(f'{path.stem}.*') if f.is_file() and f != orig]:
        ds.append(d := out/str(int(ds[-1].name)+1 if ds else 1))
        d.mkdir(exist_ok=True)
        for f in old: f.rename(d/f.name)
        if not _seen(d, path).exists(): _seen(d, path).write_bytes(orig.read_bytes())
    return ds

def _review(path, out=None, n=None):
    "`path` as a `Path`, its review folder, the original that its first review saved there, and the folder of its review `n`: the latest if `n` is None, and None when it has no review"
    path = Path(path).expanduser()
    out = Path(out).expanduser() if out else review_dir(path)
    ds = _passes(path, out)
    if n is not None and not -len(ds) <= n-(n > 0) < len(ds): raise ValueError(f'{path} has {len(ds)} reviews in {out}, so it has no review {n}')
    return path, out, out/f'{path.stem}.orig{path.suffix}', ds[-1 if n is None else n-(n > 0)] if ds else None

