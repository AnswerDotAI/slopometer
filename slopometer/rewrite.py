def py_docstrings(src):
    "Each docstring in Python source `src` as (name, text, offset): the module's first, with name None, then each function's and class's"
    lines = src.split('\n')
    starts = list(itertools.accumulate((len(l)+1 for l in lines), initial=0))
    def off(ln, col): return starts[ln-1] + len(lines[ln-1].encode()[:col].decode())  # ast columns count UTF-8 bytes
    res = []
    for nm,n in _docnodes(ast.parse(src)):
        if not (c := _doclit(n)): continue
        a = off(c.lineno, c.col_offset)
        m = re.match(r'''[a-zA-Z]*("""|\'\'\'|"|')''', src[a:])
        res.append((nm, src[a+m.end():off(c.end_lineno, c.end_col_offset)-len(m[1])], a+m.end()))
    return res

