_ctx = ('block_quote', 'code_block', 'table')

def _markup(txt):
    "Offsets of `txt`'s inline markup: each character of a link, image, emphasis, HTML tag or formula outside its text and code, spaces included and newlines left out"
    ns = mdhtml.inlines(txt)
    shown = {i for n in ns if n['type'] in ('text', 'code') for i in range(n['start'], n['end'])}
    return {i for n in ns if n['type'] not in ('text', 'code') for i in range(n['start'], n['end']) if i not in shown and txt[i] != '\n'}

def _whole(txt, mk, a, e, lo):
    "Offsets `a`,`e` of a sentence in `txt`, widened over the markup that touches it; `mk` is `_markup(txt)` and `lo` the lowest start allowed"
    while a > lo and a-1 in mk: a -= 1
    while e < len(txt) and e in mk: e += 1
    return a,e

def _visible(txt):
    "The copy of `txt` that `sentences` splits, with every offset and line where it was: each formula's characters other than whitespace become X, so that a formula reads as words in its sentence"
    out = list(txt)
    for n in mdhtml.inlines(txt):
        if n['type'] == 'math_inline': out[n['start']:n['end']] = [c if c.isspace() else 'X' for c in txt[n['start']:n['end']]]
    return ''.join(out)

def md_parts(txt):
    "Markdown `txt` in reading order as pairs: a `Sent` with its list marker, or None with the text of a heading, block quote, code block, table or YAML front matter"
    vis = _visible(txt)
    blocks = segment(vis)
    prose = [b for b in blocks if b.kind != 'heading']
    lines = txt.split('\n')
    offs = list(itertools.accumulate((len(l)+1 for l in lines), initial=0))
    res,end,para,lo,mk = [(b.start, None, txt[b.start:b.start+len(b.txt)]) for b in blocks if b.kind == 'heading'],0,None,0,_markup(txt)
    if fm := re.match(r'---\n.*?\n---[ \t]*(?=\n|\Z)', txt, re.S): res.append((0, None, fm[0]))
    for b in mdhtml.blocks(vis, nested=True):
        if b['type'] not in _ctx or b['start'] < end: continue
        end = b['end']
        res.append((offs[b['start']], None, '\n'.join(lines[b['start']:end]).rstrip()))
    for s in sentences(vis, 1):
        b = prose[s.para]
        m = _item.match(b.txt) if b.kind == 'item' and s.para != para else None
        if s.para != para: lo = b.start + (m.end() if m else 0)
