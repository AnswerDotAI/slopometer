_lead = re.compile(r'[ \t]*(?:[-*+>]|\d+[.)])?[ \t]*')
def _cut(src, ss, a, b, back):
    "Start and end of the text of `src` that deleting sentences `a` to `b` of `ss`, (docs index, `Sent`) pairs, removes. The space up to the next sentence of their paragraph goes too, or else the space back to the previous one, and a neighbour on the same line comes first. A whole paragraph takes its lines and the line breaks on one side, so its neighbours keep the wider gap, a text keeps its final line break, and no blank line is left at the start of a text or cell; no part of `SEP` goes. `back` holds the first sentence of each run already deleted with the space before it."
    (k,s0),e = ss[a],ss[b][1].end
    st = s0.start
    def near(i): return 0 <= i < len(ss) and ss[i][0] == k and ss[i][1].para == s0.para
    nxt = ss[b+1][1].start if near(b+1) and b+1 not in back else None
    prv = ss[a-1][1].end if near(a-1) else None
    for ws in (' \t', ' \t\n'):
        if nxt is not None and not src[e:nxt].strip(ws): return st,nxt
        if prv is not None and not src[prv:st].strip(ws): return prv,e
    x,y = src.rfind('\n', 0, st)+1, src.find('\n', e)
    if y < 0: y = len(src)
    if src[e:y].strip() or not _lead.fullmatch(src[x:st]): return st,e
    nb,na = 0,0
    while x-nb and src[x-nb-1] == '\n' and not src.endswith(SEP, 0, x-nb): nb += 1
    while y+na < len(src) and src[y+na] == '\n' and not src.startswith(SEP, y+na): na += 1
    first,last = x-nb == 0 or src.endswith(SEP, 0, x-nb), y+na == len(src) or src.startswith(SEP, y+na)
    return (x-nb, y+na) if first else (x-nb, y) if last or na > nb else (x, y+na)
class Rewrites:
    def __init__(self,
        src, # The text that the sentence offsets are positions in
        docs, # (name, parts) pairs, as `py_docs` returns
        answers, # (first, last, text) triples, as `parse_rewrites` returns
        valid=None, # Called with the source after each rewrite; a false result leaves that rewrite out
    ):
        ss = [(k, s) for k,(_,ps) in enumerate(docs) for s,_ in ps if s]
        self.src,self.n,self.rows,done,lo,back = src,len(ss),[],set(),len(ss),set()
        for a,b,t in sorted(answers, reverse=True):
            if not 0 <= a <= b < len(ss): continue
            done.update(range(a, b+1))
            old = ' '.join(s.text for _,s in ss[a:b+1])
            if t in ('-', old): continue
            if t.startswith('?'): kind,t = 'QUESTION',t[1:].strip()
            else:
                t = t if t.strip() else ''
                x,y = (ss[a][1].start, ss[b][1].end) if t else _cut(src, ss, a, b, back)
                new = src[:x] + t + src[y:]
                if b >= lo or len({(k, s.para) for k,s in ss[a:b+1]}) > 1 or (valid and not valid(new)): kind = 'LEFT OUT'
                else:
                    kind,src,lo = 'AFTER',new,a
                    if x < ss[a][1].start: back.add(a)
            self.rows.append((a, b, kind, old, t))
        self.new,self.missing = src,len(ss)-len(done)
        self.rows.reverse()

