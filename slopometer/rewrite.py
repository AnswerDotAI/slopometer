_defs = (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)

def _doclit(n):
    "The string literal that is the docstring of node `n`, or None"
    b = n.body
    if b and isinstance(b[0], ast.Expr) and isinstance(c := b[0].value, ast.Constant) and isinstance(c.value, str): return c

def _named(node, pre=''):
    "The function and class nodes under `node` in source order, each with its dotted name"
    for n in ast.iter_child_nodes(node):
        if isinstance(n, _defs):
            yield pre+n.name, n
            yield from _named(n, f'{pre}{n.name}.')
        else: yield from _named(n, pre)

def _docnodes(tree): return [(None, tree), *_named(tree)]

