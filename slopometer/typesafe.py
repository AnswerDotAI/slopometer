TYPESAFE_URL = 'https://api.typesafe.ai'

def systemone(
    state, # Content that every question refers to: a string, dict or list
    questions, # Question name -> question, such as `noul` returns
    model='jev-1.14.0', # Model ID or alias, such as `jev-latest`
    timeout=120, # Seconds to wait for each response
    retries=4, # Extra attempts after a 429 or 529 response
):
    "TypeSafe's response to `questions` about `state`"
    hdrs = {'Authorization': f"Bearer {os.environ['TYPESAFE_API_KEY']}"}
    for i in range(retries+1):
        r = httpx2.post(f'{TYPESAFE_URL}/v1/systemone', headers=hdrs, timeout=timeout,
            json=dict(model=model, state=state, questions=questions))
        if r.status_code not in (429, 529) or i == retries: break
        time.sleep(2**i)
    if r.is_error: raise RuntimeError(f'TypeSafe {r.status_code}: {r.text}')
    return r.json()

@delegates(systemone)
def ask_nouls(state, questions, **kwargs):
    "The probability of yes for each Noul in `questions`"
